def _source_group_requirements_block(pins: list[PinRecord]) -> list[str]:
    requirements = sorted({(source_group_label_for_pin(pin), source_group_name_for_pin(pin)) for pin in pins})
    lines = ["source_group_requirements = ["]
    for source_group_label, source_group_name in requirements:
        lines.append(f'\t("{_escape(source_group_label)}", "{_escape(source_group_name)}"),')
    lines.append("]")
    return lines


def _pin_specs_block(pins: list[PinRecord]) -> list[str]:
    lines = ["pin_specs = ["]
    for pin in pins:
        side = classify_pin_side(pin, pins)
        source_group = source_group_name_for_pin(pin)
        angle_variable = SIDE_ANGLE_VARIABLES[side]
        lines.append(
            f'\t("{_escape(pin.pin_number)}", "{_escape(pin.net_name)}", {_format_number(pin.pin_x)}, {_format_number(pin.pin_y)}, "{side}", "{_escape(source_group)}", "{angle_variable}"),'
        )
    lines.append("]")
    return lines


def _placement_loop_block() -> list[str]:
    return [
        "source_groups = validate_source_groups(source_group_requirements)",
        'log_info("Validated CIS source groups: %d" % len(source_groups))',
        'sheet_sources = set(get_objects_in_group("Sheets"))',
        "existing_object_names = get_all_model_object_names()",
        "existing_boundary_names = get_boundary_names()",
        "",
        "for pin_number, net_name, pin_x, pin_y, side_name, source_group_name, angle_variable in pin_specs:",
        '\tpin_prefix = sanitize_aedt_name("%s_%s" % (pin_number, net_name))',
        "\tsource_objects = source_groups[source_group_name]",
        "\tsheet_clones = []",
        "\tfor source_name in source_objects:",
        "\t\tclone_name = duplicate_and_get_new_object(source_name, angle_variable)",
        '\t\ttarget_base = "%s_%s_%s" % (pin_number, net_name, source_name)',
        "\t\tgenerated_name = make_unique_name(target_base, existing_object_names)",
        "\t\trename_object(clone_name, generated_name)",
        "\t\texisting_object_names.add(generated_name)",
        "\t\tset_group(generated_name, GENERATED_GROUP_NAME)",
        "\t\tmove_object(generated_name, pin_x, pin_y)",
        "\t\tif source_name in sheet_sources:",
        "\t\t\tsheet_clones.append(generated_name)",
        "\tif is_dgnd_net(net_name) and sheet_clones:",
        '\t\tperf_e_name = make_unique_name("PerfE_%s" % pin_prefix, existing_boundary_names)',
        "\t\texisting_boundary_names.add(perf_e_name)",
        "\t\tassign_perfect_e(perf_e_name, sheet_clones)",
    ]


def _boundary_runtime_block(geometry: tuple[float, float, float, float, float, float]) -> list[str]:
    start_x, start_y, width, height, z0, z1 = geometry
    return [
        f'placement_bounds_z0 = make_unique_name("PlacementBounds_Z0", existing_object_names)',
        f"create_rectangle(placement_bounds_z0, {_format_number(start_x)}, {_format_number(start_y)}, {_format_number(z0)}, {_format_number(width)}, {_format_number(height)})",
        "existing_object_names.add(placement_bounds_z0)",
        f'placement_bounds_z1 = make_unique_name("PlacementBounds_Z1", existing_object_names)',
        f"create_rectangle(placement_bounds_z1, {_format_number(start_x)}, {_format_number(start_y)}, {_format_number(z1)}, {_format_number(width)}, {_format_number(height)})",
        "existing_object_names.add(placement_bounds_z1)",
        'placement_bounds_perf_e = make_unique_name("PerfE_Placement_Bounds", existing_boundary_names)',
        "existing_boundary_names.add(placement_bounds_perf_e)",
        "assign_perfect_e(placement_bounds_perf_e, [placement_bounds_z0, placement_bounds_z1])",
    ]


def _boundary_geometry(pins: list[PinRecord]) -> tuple[tuple[float, float, float, float, float, float], str | None]:
    min_x = min(pin.pin_x for pin in pins)
    max_x = max(pin.pin_x for pin in pins)
    min_y = min(pin.pin_y for pin in pins)
    max_y = max(pin.pin_y for pin in pins)
    span_x = max_x - min_x
    span_y = max_y - min_y
    warning = None
    if span_x <= 0 or span_y <= 0:
        warning = BOUNDARY_WARNING
    width = span_x * 1.1 if span_x > 0 else 1.0
    height = span_y * 1.1 if span_y > 0 else 1.0
    center_x = (min_x + max_x) / 2
    center_y = (min_y + max_y) / 2
    start_x = center_x - width / 2
    start_y = center_y - height / 2
    return (start_x, start_y, width, height, 0.0, 1.0), warning


def _format_number(value: float | int) -> str:
    number = float(value)
    if number.is_integer():
        return str(int(number))
    return f"{number:.12g}"


def _format_angle_value(value: float | int) -> str:
    return f"{_format_number(value)}deg"


def _escape(value: object) -> str:
    return str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
