BOUNDARY_WARNING = "Coordinate span is zero on at least one axis; applied 1mm minimum boundary size."
GENERATED_GROUP_NAME = "Generated_Group"
DEFAULT_SOURCE_GROUP_NAME = "Source_Group"
SIDE_ANGLE_VARIABLES = {
    "right": "CISRotAng_Right",
    "top": "CISRotAng_Top",
    "left": "CISRotAng_Left",
    "bottom": "CISRotAng_Bottom",
}


def sanitize_aedt_name(value: object) -> str:
    text = str(value).strip()
    if not text:
        return "EMPTY"
    sanitized = re.sub(r"[^0-9A-Za-z_]+", "_", text)
    sanitized = re.sub(r"_+", "_", sanitized).strip("_")
    return sanitized or "EMPTY"


def source_group_name_for_comp_device(comp_device: str) -> str:
    return f"Source_{sanitize_aedt_name(comp_device)}"


def source_group_name_for_pin(pin: PinRecord) -> str:
    if pin.source_probe_name.strip():
        return pin.source_probe_name.strip()
    if pin.comp_device.strip():
        return source_group_name_for_comp_device(pin.comp_device)
    return DEFAULT_SOURCE_GROUP_NAME


def source_group_label_for_pin(pin: PinRecord) -> str:
    if pin.source_probe_name.strip():
        return pin.source_probe_name.strip()
    if pin.comp_device.strip():
        return pin.comp_device.strip()
    return DEFAULT_SOURCE_GROUP_NAME


def classify_pin_side(pin: PinRecord, pins: list[PinRecord]) -> str:
    if not pins:
        raise ValueError("At least one pin record is required.")
    min_x = min(record.pin_x for record in pins)
    max_x = max(record.pin_x for record in pins)
    min_y = min(record.pin_y for record in pins)
    max_y = max(record.pin_y for record in pins)
    distances = [
        ("right", abs(max_x - pin.pin_x)),
        ("top", abs(max_y - pin.pin_y)),
        ("left", abs(pin.pin_x - min_x)),
        ("bottom", abs(pin.pin_y - min_y)),
    ]
    return min(distances, key=lambda item: item[1])[0]


def build_script(
    pins: list[PinRecord],
    options: GenerationOptions | None = None,
) -> GenerationResult:
    if not pins:
        raise ValueError("At least one pin record is required.")
    options = options or GenerationOptions()

    warnings: list[str] = []
    boundary_geometry, boundary_warning = _boundary_geometry(pins)
    if boundary_warning:
        warnings.append(boundary_warning)

    lines: list[str] = [
        "# -*- coding: utf-8 -*-",
        "# ----------------------------------------------",
        f"# Script generated by CIS Probe Placement Scriptor v{__version__}",
        "# Target: Ansys Electronics Desktop / HFSS IronPython",
        "# Source objects must be placed in HFSS groups named by Source_probe name, or Source_Group when omitted.",
        "# ----------------------------------------------",
        "import re",
        "import ScriptEnv",
        "",
        'ScriptEnv.Initialize("Ansoft.ElectronicsDesktop")',
        "oDesktop.RestoreWindow()",
        f'PROJECT_NAME = "{_escape(options.project_name)}"',
        f'DESIGN_NAME = "{_escape(options.design_name)}"',
        f'GENERATED_GROUP_NAME = "{GENERATED_GROUP_NAME}"',
        'oProject = oDesktop.SetActiveProject(PROJECT_NAME)',
        'oDesign = oProject.SetActiveDesign(DESIGN_NAME)',
        'oEditor = oDesign.SetActiveEditor("3D Modeler")',
        'oBoundaryModule = oDesign.GetModule("BoundarySetup")',
        "",
    ]
    lines.extend(_runtime_helper_block())
    lines.append("")
    lines.append(
        f'ensure_design_variable("CISRotAng_Right", "{_escape(_format_angle_value(options.right_rotation_angle))}")'
    )
    lines.append(
        f'ensure_design_variable("CISRotAng_Top", "{_escape(_format_angle_value(options.top_rotation_angle))}")'
    )
    lines.append(
        f'ensure_design_variable("CISRotAng_Left", "{_escape(_format_angle_value(options.left_rotation_angle))}")'
    )
    lines.append(
        f'ensure_design_variable("CISRotAng_Bottom", "{_escape(_format_angle_value(options.bottom_rotation_angle))}")'
    )
    lines.append("")
    lines.extend(_source_group_requirements_block(pins))
    lines.append("")
    lines.extend(_pin_specs_block(pins))
    lines.append("")
    lines.extend(_placement_loop_block())
    lines.append("")
    lines.extend(_boundary_runtime_block(boundary_geometry))
    lines.append("")

    return GenerationResult(script="\n".join(lines), name_mappings=[], warnings=warnings)


