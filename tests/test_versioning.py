from pathlib import Path

from cisprobeplace import __version__
from cisprobeplace.gui import APP_TITLE
from cisprobeplace.models import PinRecord
from cisprobeplace.script_builder import build_script


def test_app_installer_and_generated_script_versions_match():
    assert __version__ == "0.1.3"
    assert APP_TITLE == f"CIS Probe Placement Scriptor v{__version__}"

    installer_script = Path("CISProbePlacementScriptor.iss").read_text(encoding="utf-8")
    assert f'#define AppVersion "{__version__}"' in installer_script
    assert "AppVersion={#AppVersion}" in installer_script
    assert "OutputBaseFilename=CISProbePlacementScriptorSetup-{#AppVersion}" in installer_script

    result = build_script([PinRecord("", "1", "", "", "", 0.0, 0.0, "N1")])
    assert f"Script generated by CIS Probe Placement Scriptor v{__version__}" in result.script
