from pathlib import Path

from cisprobeplace import __version__
from cisprobeplace.gui import APP_TITLE
from cisprobeplace.models import PinRecord
from cisprobeplace.script_builder import build_script


def test_app_installer_and_generated_script_versions_match():
    assert __version__ == "0.3.4"
    assert APP_TITLE == f"CIS Probe Placement Scriptor v{__version__}"

    repository_root = Path(__file__).resolve().parents[1]
    installer_script = (repository_root / "CISProbePlacementScriptor.iss").read_text(encoding="utf-8")
    assert f'#define AppVersion "{__version__}"' in installer_script
    assert "AppVersion={#AppVersion}" in installer_script
    assert "OutputBaseFilename=CISProbePlacementScriptorSetup-{#AppVersion}" in installer_script

    result = build_script([PinRecord("", "1", "", "", "", 0.0, 0.0, "N1")])
    assert f"Script generated by CIS Probe Placement Scriptor v{__version__}" in result.script


def test_installer_removes_the_previous_program_files_before_installing():
    repository_root = Path(__file__).resolve().parents[1]
    installer_script = (repository_root / "CISProbePlacementScriptor.iss").read_text(encoding="utf-8")

    # Files left by an older version share the folder with the new one; a
    # leftover package folder once kept the application from starting.
    assert '[InstallDelete]\nType: filesandordirs; Name: "{app}\\_internal"' in installer_script
    assert installer_script.index("[InstallDelete]") < installer_script.index("[Files]")


def test_build_leaves_out_optional_packages_of_openpyxl():
    repository_root = Path(__file__).resolve().parents[1]
    spec = (repository_root / "CISProbePlacementScriptor.spec").read_text(encoding="utf-8")

    # 0.1.4 was built where these were installed and shipped all of them.
    assert "excludes=['numpy', 'pandas', 'lxml', 'PIL']" in spec
